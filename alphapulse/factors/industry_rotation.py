# Build reverse index: stock_code -> industry
_STOCK_INDUSTRY_MAP = {}
for _ind, _codes in _CODE_RANGE_INDUSTRY.items():
    for _c in _codes:
        _STOCK_INDUSTRY_MAP[_c] = _ind


def get_industry(code: str) -> str:
    """Get Shenwan level-1 industry for a stock code."""
    code = str(code).zfill(6)
    if code in _STOCK_INDUSTRY_MAP:
        return _STOCK_INDUSTRY_MAP[code]
    # Fallback: use code prefix
    if code.startswith("688"):
        return "电子"  # STAR market mostly tech
    elif code.startswith(("300", "301")):
        return "计算机"  # ChiNext mostly tech
    elif code.startswith("600"):
        return "银行"  # conservative guess for unmatched SH stocks
    elif code.startswith(("000", "001", "002", "003")):
        return "电子"  # conservative guess for unmatched SZ stocks
    return "其他"


def load_industry_map() -> dict:
    """Load cached industry map if exists."""
    if _INDUSTRY_CACHE.exists():
        with open(_INDUSTRY_CACHE) as f:
            return json.load(f)
    return _STOCK_INDUSTRY_MAP


def build_industry_index(
    stocks: dict[str, pd.DataFrame],
    industry_map: dict[str, str] | None = None,
) -> dict[str, pd.DataFrame]:
    """Build equal-weight industry indices from constituent returns.

    Args:
        stocks: symbol -> DataFrame (OHLCV with date index)
        industry_map: symbol -> industry name, uses built-in if None

    Returns:
        industry -> DataFrame with columns: close, return, constituents
    """
    if industry_map is None:
        industry_map = _STOCK_INDUSTRY_MAP

    # Group stocks by industry
    industry_stocks = defaultdict(list)
    for sym in stocks:
        ind = get_industry(sym)
        industry_stocks[ind].append(sym)

    indices = {}
    for ind, syms in industry_stocks.items():
        if len(syms) < 3:
            continue
        # Collect close prices for all constituents
        closes = {}
        for sym in syms:
            df = stocks[sym]
            if "close" in df.columns and len(df) > 60:
                closes[sym] = df["close"]
        if len(closes) < 3:
            continue
        # Align on dates
        all_closes = pd.DataFrame(closes).dropna()
        if len(all_closes) < 60:
            continue
        # Equal-weight index
        daily_returns = all_closes.pct_change().mean(axis=1)
        index_level = (1 + daily_returns).cumprod() * 1000
        indices[ind] = pd.DataFrame({
            "close": index_level,
            "return": daily_returns,
            "constituent_count": len(closes),
        }, index=all_closes.index)
    return indices


def score_industry_trend(
    index_df: pd.DataFrame,
    ma_periods: tuple = (5, 10, 20, 60),
    mom_periods: tuple = (20, 60, 120),
    macd_params: tuple = (12, 26, 9),
) -> dict:
    """Score a single industry index for trend strength.

    Scoring dimensions:
    1. MA alignment (均线多头排列): MA5>MA10>MA20>MA60
    2. MACD strength: DIF position and direction
    3. Returns momentum (收益率动量): recent relative strength
    4. Consistency: days above MA20 ratio

    Returns dict of scores (0-1 normalized).
    """
    close = index_df["close"]
    if len(close) < 120:
        return {"total": 0, "ma_score": 0, "macd_score": 0, "mom_score": 0, "consistency": 0}

    # 1. MA alignment score
    mas = {}
    for p in ma_periods:
        mas[p] = close.rolling(p).mean()
    latest = {p: mas[p].iloc[-1] for p in ma_periods}
    ma_bullish = all(
        latest[ma_periods[i]] > latest[ma_periods[i + 1]]
        for i in range(len(ma_periods) - 1)
        if not pd.isna(latest[ma_periods[i]]) and not pd.isna(latest[ma_periods[i + 1]])
    )
    # Partial alignment score
    align_pairs = 0
    total_pairs = 0
    for i in range(len(ma_periods) - 1):
        for j in range(i + 1, len(ma_periods)):
            if not pd.isna(latest[ma_periods[i]]) and not pd.isna(latest[ma_periods[j]]):
                total_pairs += 1
                if latest[ma_periods[i]] > latest[ma_periods[j]]:
                    align_pairs += 1
    ma_score = align_pairs / max(total_pairs, 1)

    # 2. MACD score
    ema_fast = close.ewm(span=macd_params[0]).mean()
    ema_slow = close.ewm(span=macd_params[1]).mean()
    dif = ema_fast - ema_slow
    dea = dif.ewm(span=macd_params[2]).mean()
    hist = (dif - dea) * 2
    # DIF above DEA, DIF above 0, histogram positive
    macd_score = 0.0
    if dif.iloc[-1] > 0:
        macd_score += 0.4
    if dif.iloc[-1] > dea.iloc[-1]:
        macd_score += 0.3
    if hist.iloc[-1] > 0:
        macd_score += 0.3

    # 3. Momentum score: recent returns vs longer-term
    returns = index_df["return"].dropna()
    if len(returns) >= 120:
        mom_short = returns.iloc[-mom_periods[0]:].mean() if len(returns) >= mom_periods[0] else 0
        mom_mid = returns.iloc[-mom_periods[1]:].mean() if len(returns) >= mom_periods[1] else 0
        mom_long = returns.iloc[-mom_periods[2]:].mean() if len(returns) >= mom_periods[2] else 0
        # Stronger momentum = higher score
        mom_raw = mom_short * 2 + mom_mid + mom_long * 0.5
        mom_score = 1.0 / (1.0 + np.exp(-mom_raw * 100))  # sigmoid normalize
    else:
        mom_score = 0.5

    # 4. Consistency: fraction of days close > MA20
    if len(close) >= 20:
        ma20 = close.rolling(20).mean()
        above_ma20 = (close > ma20).mean()
        consistency = above_ma20
    else:
        consistency = 0.5

    # Weighted total
    total = 0.30 * ma_score + 0.25 * macd_score + 0.25 * mom_score + 0.20 * consistency
    return {
        "total": round(total, 4),
        "ma_score": round(ma_score, 4),
        "macd_score": round(macd_score, 4),
        "mom_score": round(mom_score, 4),
        "consistency": round(consistency, 4),
    }


def rank_industries(
    stocks: dict[str, pd.DataFrame],
    min_constituents: int = 5,
    top_n: int = 5,
) -> list[dict]:
    """Stage 1: Rank all industries by trend strength, return top N.

    Args:
        stocks: symbol -> DataFrame
        min_constituents: minimum stocks per industry
        top_n: number of mainline industries to return

    Returns:
        List of {industry, score, ...} sorted by total score descending
    """
    indices = build_industry_index(stocks)
    rankings = []
    for ind, idx_df in indices.items():
        n_constituents = int(idx_df["constituent_count"].iloc[-1]) if "constituent_count" in idx_df.columns else 0
        if n_constituents < min_constituents:
            continue
        scores = score_industry_trend(idx_df)
        rankings.append({
            "industry": ind,
            "constituents": n_constituents,
            **scores,
        })
    rankings.sort(key=lambda x: x["total"], reverse=True)
    return rankings[:top_n]


def get_industry_constituents(
    stocks: dict[str, pd.DataFrame],
    industry: str,
) -> list[str]:
    """Get stock symbols belonging to an industry."""
    return [s for s in stocks if get_industry(s) == industry]
